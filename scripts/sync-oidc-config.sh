#!/usr/bin/env bash
# Pulls the OIDC client_id registered by the zitadel-register-client Job
# (ConfigMap/harpia-oidc-config) and writes it to frontend/.env.local so the
# Vite dev server picks it up as PUBLIC_ZITADEL_CLIENT_ID.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$REPO_ROOT/frontend/.env.local"

if ! kubectl get configmap harpia-oidc-config >/dev/null 2>&1; then
  echo "ERROR: ConfigMap 'harpia-oidc-config' not found. Run the zitadel-register-client Job first." >&2
  exit 1
fi

CLIENT_ID=$(kubectl get configmap harpia-oidc-config -o jsonpath='{.data.clientId}')
ISSUER=$(kubectl get configmap harpia-oidc-config -o jsonpath='{.data.issuer}')

if [[ -z "$CLIENT_ID" ]]; then
  echo "ERROR: ConfigMap missing 'clientId'. Re-run the Job." >&2
  exit 1
fi

cat >"$ENV_FILE" <<EOF
# Generated by scripts/sync-oidc-config.sh — do not edit by hand.
PUBLIC_ZITADEL_CLIENT_ID=$CLIENT_ID
PUBLIC_ZITADEL_ISSUER=${ISSUER:-http://localhost:8085}
EOF

echo "Wrote $ENV_FILE"
echo "  PUBLIC_ZITADEL_CLIENT_ID=$CLIENT_ID"
echo "Tilt restarts the vite local_resource when this file changes."
